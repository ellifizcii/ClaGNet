# =============================================================================
# MAIN
# =============================================================================

def main():
    args = build_args()

    os.makedirs(
        args.output_dir,
        exist_ok=True
    )

    if args.device == "cuda" and not torch.cuda.is_available():
        raise RuntimeError(
            "CUDA istendi ama bu bilgisayarda kullanilamiyor."
        )

    device = torch.device(
        "cuda"
        if (
            args.device == "cuda"
            or (
                args.device == "auto"
                and torch.cuda.is_available()
            )
        )
        else "cpu"
    )

    print("Device:", device)
    print("Data directory:", args.data_dir)

    print(
        "Runs:", args.n_runs,
        "| Pretrain max epochs:", args.pretrain_epochs,
        "| PROSER epochs:", args.proser_epochs,
        "| Batch:", args.batch_size,
        "| alpha:", args.proser_alpha,
        "| lambda1:", args.proser_lambda1,
        "| lambda2:", args.proser_lambda2,
        "| dummy:", args.dummy_number,
        "| score T:", args.score_temperature,
        "| known reject rate:", args.known_reject_rate
    )

    if args.dummy_number != 1:
        raise ValueError(
            "Bu makale uyarlamasi official default olan DUMMY_NUMBER=1 "
            "icin sabitlenmistir."
        )

    if not os.path.isdir(args.data_dir):
        raise FileNotFoundError(
            f"DATA_DIR bulunamadi:\n{args.data_dir}\n\n"
            "Dosyanin ust kismindaki DATA_DIR yolunu kontrol edin."
        )

    rows = []

    for ds in DATASETS:
        print("\n" + "#" * 96)
        print(
            f"{ds['name']} | "
            f"matrix={ds['matrix']} | "
            f"labels={ds['labels']} | "
            f"known={ds['n_known']} | "
            f"total={ds['n_total']}"
        )
        print("#" * 96)

        try:
            Xdf, y = load_scrna(
                os.path.join(
                    args.data_dir,
                    ds["matrix"]
                ),
                os.path.join(
                    args.data_dir,
                    ds["labels"]
                ),
                ds["name"]
            )
        except Exception as e:
            print(
                "SKIP",
                ds["name"],
                type(e).__name__,
                e
            )
            continue

        classes = sorted(
            np.unique(y)
        )

        if len(classes) < ds["n_known"]:
            print(
                f"SKIP {ds['name']}: "
                f"actual class count={len(classes)}, "
                f"n_known={ds['n_known']} cannot be used."
            )
            continue

        for run in range(args.n_runs):
            seed = (
                args.base_seed
                + 17 * run
            )

            # Same class-selection seed convention as other baselines.
            rng = np.random.default_rng(
                args.base_seed
                + 13 * run
            )

            known = sorted(
                rng.choice(
                    classes,
                    ds["n_known"],
                    replace=False
                ).tolist()
            )

            open_ = [
                c
                for c in classes
                if c not in known
            ]

            print(
                f"\n[{ds['name']}] "
                f"Run {run + 1}/{args.n_runs} "
                f"Known={known} "
                f"Open={open_}"
            )

            try:
                io, iv, itk, itu = split_indices(
                    y,
                    known,
                    open_,
                    seed,
                    args.test_size,
                    args.val_size,
                    args.unknown_sampling
                )

                Xo, Xv, Xk, Xu, genes = preprocess_train_only(
                    Xdf,
                    io,
                    iv,
                    itk,
                    itu,
                    args.n_top_genes
                )

                yo = y[io]
                yv = y[iv]
                yk = y[itk]

                global_to_local = {
                    c: i
                    for i, c in enumerate(known)
                }

                yol = np.array(
                    [
                        global_to_local[c]
                        for c in yo
                    ],
                    dtype=int
                )

                yvl = np.array(
                    [
                        global_to_local[c]
                        for c in yv
                    ],
                    dtype=int
                )

                # ---------------------------------------------------------
                # 1) Closed-set pretraining on KNOWN cells only
                # ---------------------------------------------------------
                net, best_epoch = pretrain_closed_set(
                    Xo,
                    yol,
                    Xv,
                    yvl,
                    len(known),
                    device,
                    seed,
                    args
                )

                # ---------------------------------------------------------
                # 2) PROSER placeholder fine-tuning on optimization cells
                #    only. No final unknown cells enter this stage.
                # ---------------------------------------------------------
                net = proser_finetune(
                    net,
                    Xo,
                    yol,
                    device,
                    seed,
                    args
                )

                # ---------------------------------------------------------
                # 3) KNOWN-ONLY DeltaP threshold calibration
                #
                # Official PROSER evaluates DeltaP primarily by AUROC and does
                # not prescribe a universal hard threshold. We therefore use
                # the same known-only 5% lower-tail calibration convention as
                # the ARPL baseline for Ao/AKS/AUS/NA.
                # ---------------------------------------------------------
                threshold = calibrate_known_threshold(
                    net,
                    Xv,
                    device,
                    args.score_temperature,
                    args.known_reject_rate
                )

                # ---------------------------------------------------------
                # 4) FINAL TEST
                # ---------------------------------------------------------
                Xtest = np.vstack(
                    [Xk, Xu]
                )

                ytest = np.r_[
                    yk,
                    np.full(
                        len(Xu),
                        UNKNOWN,
                        dtype=int
                    )
                ]

                pred, score = predict_global(
                    net,
                    Xtest,
                    known,
                    device,
                    threshold,
                    args.score_temperature
                )

                m = metrics(
                    ytest,
                    pred,
                    score
                )

                row = {
                    "Dataset": ds["name"],
                    "Method": "PROSER-DeltaP-Calibrated",
                    "Run": run + 1,
                    "Seed": seed,
                    "Best_Pretrain_Epoch": best_epoch,
                    "Known_Classes": "|".join(
                        map(str, known)
                    ),
                    "Open_Classes": "|".join(
                        map(str, open_)
                    ),
                    "PROSER_Epochs": args.proser_epochs,
                    "PROSER_Alpha": args.proser_alpha,
                    "PROSER_Lambda1": args.proser_lambda1,
                    "PROSER_Lambda2": args.proser_lambda2,
                    "PROSER_MixWeight": args.proser_mix_weight,
                    "Dummy_Number": args.dummy_number,
                    "Score_Temperature": args.score_temperature,
                    "Known_Reject_Rate": args.known_reject_rate,
                    "DeltaP_Known_Threshold": threshold,
                    **m
                }

                rows.append(row)

                print(
                    f"  -> Ao={m['Ao']:.4f} "
                    f"AKS={m['AKS']:.4f} "
                    f"AUS={m['AUS']:.4f} "
                    f"NA={m['NA']:.4f} "
                    f"AUROC={m['AUROC']:.4f} "
                    f"F1={m['F1_macro']:.4f} "
                    f"| DeltaP_thr={threshold:.8f}"
                )

                pd.DataFrame(
                    rows
                ).to_csv(
                    os.path.join(
                        args.output_dir,
                        "proser_all_runs.csv"
                    ),
                    index=False
                )

            except Exception as e:
                print(
                    "  RUN ERROR:",
                    type(e).__name__,
                    e
                )

    if rows:
        df = pd.DataFrame(
            rows
        )

        summary = summarize(
            df
        )

        df.to_csv(
            os.path.join(
                args.output_dir,
                "proser_all_runs.csv"
            ),
            index=False
        )

        summary.to_csv(
            os.path.join(
                args.output_dir,
                "proser_summary.csv"
            ),
            index=False
        )

        print_summary(
            summary
        )

        print(
            "\nOutput folder:",
            os.path.abspath(
                args.output_dir
            )
        )
    else:
        print(
            "\nNo successful run was produced."
        )


if __name__ == "__main__":
    main()
