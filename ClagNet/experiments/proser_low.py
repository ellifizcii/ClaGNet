def proser_finetune(
    net,
    Xo,
    yo,
    device,
    seed,
    args
):
    """
    Official PROSER training structure adapted from traindummy():

      beta ~ Beta(alpha, alpha)
      first half -> manifold mixup -> placeholder target
      second half -> normal known CE
      second half -> suppress true class, then placeholder CE

      loss = 0.01*loss1 + lambda1*loss2 + lambda2*loss3
    """
    seed_all(seed + 100000)

    dl = make_loader(
        Xo, yo,
        args.batch_size,
        True
    )

    # Official code: SGD, lr * 0.01, momentum=.9, weight_decay=5e-4
    optimizer = torch.optim.SGD(
        net.parameters(),
        lr=args.lr * args.proser_lr_factor,
        momentum=0.9,
        weight_decay=5e-4
    )

    criterion = nn.CrossEntropyLoss()

    net.train()

    for ep in range(1, args.proser_epochs + 1):
        net.train()

        loss_sum = 0.0
        l1_sum = 0.0
        l2_sum = 0.0
        l3_sum = 0.0
        nb = 0

        for xb, yb in dl:
            # Need at least two examples in each half for stable BatchNorm.
            if len(xb) < 4:
                continue

            xb = xb.to(device)
            yb = yb.to(device)

            half = len(xb) // 2

            first_x = xb[:half]
            first_y = yb[:half]

            second_x = xb[half:]
            second_y = yb[half:]

            # -------------------------------------------------------------
            # Data placeholder: manifold mixup in hidden space
            # -------------------------------------------------------------
            beta = torch.distributions.Beta(
                args.proser_alpha,
                args.proser_alpha
            ).sample().to(device)

            first_hidden = net.pre_mix(first_x)

            perm = torch.randperm(
                first_hidden.size(0),
                device=device
            )

            mixed_hidden = (
                beta * first_hidden
                + (1.0 - beta) * first_hidden[perm]
            )

            mixed_known, mixed_dummy = net.logits_from_hidden(
                mixed_hidden
            )

            mixed_all = torch.cat(
                [mixed_known, mixed_dummy],
                dim=1
            )

            # The placeholder target is index K because DUMMY_NUMBER=1.
            dummy_target_first = torch.full(
                (len(first_x),),
                fill_value=mixed_known.shape[1],
                dtype=torch.long,
                device=device
            )

            loss1 = criterion(
                mixed_all,
                dummy_target_first
            )

            # -------------------------------------------------------------
            # Ordinary known-class classification
            # -------------------------------------------------------------
            second_known, second_dummy = net(
                second_x
            )

            second_all = torch.cat(
                [second_known, second_dummy],
                dim=1
            )

            loss2 = criterion(
                second_all,
                second_y
            )

            # -------------------------------------------------------------
            # Classifier placeholder loss:
            # remove the target known logit and force the best alternative
            # to be the reserved dummy class.
            # -------------------------------------------------------------
            max_dummy, _ = torch.max(
                second_dummy,
                dim=1,
                keepdim=True
            )

            dummy_outputs = torch.cat(
                [
                    second_known.clone(),
                    max_dummy
                ],
                dim=1
            )

            dummy_outputs[
                torch.arange(
                    len(second_y),
                    device=device
                ),
                second_y
            ] = -1e9

            dummy_target_second = torch.full(
                (len(second_x),),
                fill_value=second_known.shape[1],
                dtype=torch.long,
                device=device
            )

            loss3 = criterion(
                dummy_outputs,
                dummy_target_second
            )

            loss = (
                args.proser_mix_weight * loss1
                + args.proser_lambda1 * loss2
                + args.proser_lambda2 * loss3
            )

            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            optimizer.step()

            loss_sum += loss.item()
            l1_sum += loss1.item()
            l2_sum += loss2.item()
            l3_sum += loss3.item()
            nb += 1

        print(
            f"      PROSER epoch {ep:02d}/{args.proser_epochs} "
            f"loss={loss_sum/max(nb,1):.4f} "
            f"Lmix={l1_sum/max(nb,1):.4f} "
            f"Lknown={l2_sum/max(nb,1):.4f} "
            f"Ldummy={l3_sum/max(nb,1):.4f}"
        )

    return net


