@torch.no_grad()
def get_proser_outputs(
    net,
    X,
    device,
    temperature=1024.0
):
    net.eval()

    dl = make_loader(
        X,
        np.zeros(len(X), dtype=int),
        min(512, len(X)),
        False
    )

    all_known_logits = []
    all_dummy_logits = []

    for xb, _ in dl:
        xb = xb.to(device)

        known_logits, dummy_logits = net(xb)

        all_known_logits.append(
            known_logits.cpu().numpy()
        )

        all_dummy_logits.append(
            dummy_logits.cpu().numpy()
        )

    known_logits = np.vstack(
        all_known_logits
    )

    dummy_logits = np.vstack(
        all_dummy_logits
    )

    # Original implementation reduces multiple dummy classifiers with max.
    max_dummy = np.max(
        dummy_logits,
        axis=1,
        keepdims=True
    )

    total_logits = np.concatenate(
        [known_logits, max_dummy],
        axis=1
    )

    best_known_idx = np.argmax(
        known_logits,
        axis=1
    )

    dummy_logit = max_dummy[:, 0]

    # DeltaP exactly follows the official PROSER evaluation construction:
    #   unknown_confidence = dummy_probability - max_known_probability
    # Here we negate it so that a larger score consistently means "known".
    scaled = total_logits / float(temperature)

    scaled = scaled - np.max(
        scaled,
        axis=1,
        keepdims=True
    )

    probs = np.exp(scaled)
    probs = probs / np.sum(
        probs,
        axis=1,
        keepdims=True
    )

    max_known_prob = np.max(
        probs[:, :-1],
        axis=1
    )

    dummy_prob = probs[:, -1]

    knownness_score = (
        max_known_prob
        - dummy_prob
    )

    return (
        best_known_idx,
        knownness_score,
        known_logits,
        dummy_logit
    )


def calibrate_known_threshold(
    net,
    Xval,
    device,
    temperature=1024.0,
    reject_rate=0.05
):
    """
    PROSER itself supplies the DeltaP score, but its official unknown-detection
    script reports AUROC rather than a universal hard threshold.

    For this study's hard OSR metrics, calibrate the lower tail of DeltaP
    knownness using KNOWN validation cells only.

    threshold = 5th percentile when reject_rate=0.05
    reject test cell iff knownness_score < threshold.
    """
    (
        _,
        score,
        _,
        _
    ) = get_proser_outputs(
        net,
        Xval,
        device,
        temperature
    )

    threshold = float(
        np.quantile(
            score,
            reject_rate
        )
    )

    return threshold


def predict_global(
    net,
    X,
    known,
    device,
    threshold,
    temperature=1024.0
):
    (
        local_pred,
        score,
        _,
        _
    ) = get_proser_outputs(
        net,
        X,
        device,
        temperature
    )

    known = np.asarray(
        sorted(known),
        dtype=int
    )

    pred = known[
        local_pred
    ].copy()

    pred[
        score < threshold
    ] = UNKNOWN

    return pred, score


