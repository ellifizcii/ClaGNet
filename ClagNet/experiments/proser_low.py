def pretrain_closed_set(
    Xo, yo, Xv, yv,
    n_classes,
    device,
    seed,
    args
):
    seed_all(seed)

    net = PROSERNet(
        input_dim=Xo.shape[1],
        n_classes=n_classes,
        hidden=args.hidden_dim,
        latent=args.latent_dim,
        drop=args.dropout,
        dummy_number=args.dummy_number
    ).to(device)

    # The placeholder is not optimized in closed-set pretraining.
    for p in net.dummy_clf.parameters():
        p.requires_grad = False

    dl = make_loader(
        Xo, yo,
        args.batch_size,
        True
    )

    vl = make_loader(
        Xv, yv,
        min(512, len(Xv)),
        False
    )

    optimizer = torch.optim.AdamW(
        [p for p in net.parameters() if p.requires_grad],
        lr=args.lr,
        weight_decay=args.weight_decay
    )

    best = float("inf")
    best_state = None
    best_epoch = 0
    bad = 0

    for ep in range(1, args.pretrain_epochs + 1):
        net.train()

        for xb, yb in dl:
            # BatchNorm safety
            if len(xb) < 2:
                continue

            xb = xb.to(device)
            yb = yb.to(device)

            optimizer.zero_grad(set_to_none=True)

            known_logits, _ = net(xb)
            loss = F.cross_entropy(
                known_logits,
                yb
            )

            loss.backward()
            optimizer.step()

        net.eval()

        total_loss = 0.0
        n = 0

        with torch.no_grad():
            for xb, yb in vl:
                xb = xb.to(device)
                yb = yb.to(device)

                known_logits, _ = net(xb)
                loss = F.cross_entropy(
                    known_logits,
                    yb
                )

                total_loss += loss.item() * len(xb)
                n += len(xb)

        val_loss = total_loss / max(n, 1)

        if val_loss < best - 1e-5:
            best = val_loss
            best_epoch = ep
            bad = 0
            best_state = {
                k: v.detach().cpu().clone()
                for k, v in net.state_dict().items()
            }
        else:
            bad += 1

        if ep == 1 or ep % 10 == 0:
            print(
                f"      pretrain epoch {ep:03d} "
                f"val_CE={val_loss:.4f}"
            )

        if bad >= args.patience:
            break

    if best_state is not None:
        net.load_state_dict(best_state)

    # Reinitialize placeholder exactly at start of PROSER fine-tuning,
    # analogous to replacing clf2 in the official implementation.
    net.dummy_clf.reset_parameters()

    for p in net.dummy_clf.parameters():
        p.requires_grad = True

    print(
        f"      selected pretrain epoch={best_epoch} "
        f"best_val_CE={best:.4f}"
    )

    return net, best_epoch


