class ResBlock(nn.Module):
    def __init__(self, d, drop):
        super().__init__()
        self.f1 = nn.Linear(d, d)
        self.b1 = nn.BatchNorm1d(d)
        self.f2 = nn.Linear(d, d)
        self.b2 = nn.BatchNorm1d(d)
        self.drop = nn.Dropout(drop)

    def forward(self, x):
        r = x
        x = self.drop(F.gelu(self.b1(self.f1(x))))
        x = self.b2(self.f2(x))
        return F.gelu(x + r)


class PROSERNet(nn.Module):
    """
    Residual-MLP adaptation of the WideResNet used by original PROSER.

    'pre_mix' corresponds conceptually to the feature stage before the
    original layer3. Manifold mixup is performed there.
    """

    def __init__(
        self,
        input_dim,
        n_classes,
        hidden=256,
        latent=64,
        drop=0.25,
        dummy_number=1
    ):
        super().__init__()

        self.stem = nn.Sequential(
            nn.Linear(input_dim, 512),
            nn.BatchNorm1d(512),
            nn.GELU(),
            nn.Dropout(drop),
            nn.Linear(512, hidden),
            nn.BatchNorm1d(hidden),
            nn.GELU()
        )

        self.r1 = ResBlock(hidden, drop)
        self.r2 = ResBlock(hidden, drop)

        self.latent_head = nn.Sequential(
            nn.Linear(hidden, 128),
            nn.BatchNorm1d(128),
            nn.GELU(),
            nn.Dropout(drop),
            nn.Linear(128, latent)
        )

        # Known-class classifier
        self.known_clf = nn.Linear(
            latent,
            n_classes
        )

        # Classifier placeholder(s)
        self.dummy_clf = nn.Linear(
            latent,
            dummy_number
        )

    def pre_mix(self, x):
        return self.r1(
            self.stem(x)
        )

    def post_mix(self, h):
        h = self.r2(h)
        return self.latent_head(h)

    def encode(self, x):
        return self.post_mix(
            self.pre_mix(x)
        )

    def known_logits(self, x):
        return self.known_clf(
            self.encode(x)
        )

    def dummy_logits(self, x):
        return self.dummy_clf(
            self.encode(x)
        )

    def logits_from_hidden(self, h):
        z = self.post_mix(h)
        return self.known_clf(z), self.dummy_clf(z)

    def forward(self, x):
        z = self.encode(x)
        return self.known_clf(z), self.dummy_clf(z)


