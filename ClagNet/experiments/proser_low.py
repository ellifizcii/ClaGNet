"""
PROSER baseline adapted to leakage-free scRNA-seq open-set cell annotation.

Method:
    Zhou, Ye, Zhan. "Learning Placeholders for Open-Set Recognition"
    CVPR 2021.

Official repository:
    https://github.com/LAMDA-CL/CVPR21-Proser

This adaptation keeps the central PROSER mechanisms from the official
unknown-detection code:
  1) closed-set pretraining on known classes,
  2) one classifier placeholder ("dummy" classifier),
  3) data placeholders generated by manifold mixup,
  4) three PROSER fine-tuning losses:
       loss = 0.01 * loss_mix + lambda1 * loss_known + lambda2 * loss_dummy,
  5) Beta(alpha, alpha) mix coefficient, alpha=1,
  6) lambda1=lambda2=1,
  7) 10 PROSER fine-tuning epochs.

scRNA-seq adaptations:
  - Residual MLP backbone instead of WideResNet.
  - Manifold mixup is performed in the hidden representation.
  - Same leakage-free known/open protocol, preprocessing, seeds, and metrics
    used in this study.
  - Final unknown classes are NEVER used in training, early stopping,
    preprocessing fitting, or calibration.
  - The official PROSER unknown-detection code evaluates DeltaP by AUROC
    and does NOT define a universal hard unknown decision threshold.
  - Because this scRNA-seq study also reports Ao/AKS/AUS/NA, hard rejection
    is obtained from the SAME DeltaP score using a KNOWN-ONLY calibration set.
    The lower 5% quantile of known validation DeltaP-knownness is used as the
    acceptance threshold. Final unknown cells are NEVER used to select it.
  - AUROC uses the official PROSER DeltaP construction:
        knownness = max_known_probability - dummy_probability
    so larger score means "known". As in the official code, temperature 1024
    is used for DeltaP scoring.

Outputs:
    proser_all_runs.csv
    proser_summary.csv
"""

