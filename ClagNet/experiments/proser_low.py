def metrics(y, p, score):
    kn = y != UNKNOWN
    un = ~kn

    yk = y[kn]
    pk = p[kn]
    pu = p[un]

    TP = np.sum(pk == yk)
    FN = np.sum(pk != yk)
    TU = np.sum(pu == UNKNOWN)
    FU = np.sum(pu != UNKNOWN)

    n = len(y)

    Ao = (TP + TU) / n if n else 0.0
    AKS = TP / (TP + FN) if (TP + FN) else 0.0
    AUS = TU / (TU + FU) if (TU + FU) else 0.0
    FAR = FU / (TU + FU) if (TU + FU) else 0.0
    FRR = FN / (TP + FN) if (TP + FN) else 0.0
    NA = 0.5 * (AKS + AUS)

    labs = sorted(
        np.unique(
            y[y != UNKNOWN]
        )
    )

    F1 = f1_score(
        y,
        p,
        labels=labs,
        average="macro",
        zero_division=0
    )

    try:
        AUROC = roc_auc_score(
            (y != UNKNOWN).astype(int),
            score
        )
    except Exception:
        AUROC = np.nan

    return dict(
        Ao=Ao,
        AKS=AKS,
        AUS=AUS,
        NA=NA,
        FAR=FAR,
        FRR=FRR,
        F1_macro=F1,
        AUROC=AUROC
    )


def summarize(df):
    rows = []

    for name, g in df.groupby("Dataset"):
        row = {
            "Dataset": name,
            "Method": "PROSER-DeltaP-Calibrated",
            "N_Runs": len(g)
        }

        for m in METRICS:
            row[m + "_mean"] = g[m].mean()
            row[m + "_std"] = g[m].std(ddof=0)

        rows.append(row)

    return pd.DataFrame(rows)


